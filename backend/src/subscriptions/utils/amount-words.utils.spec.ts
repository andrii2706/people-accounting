import { describe, expect, it } from 'vitest';
import { amountInWords, money } from './amount-words.utils.js';

describe('сума прописом', () => {
  it.each([
    [1, 'Одна гривня 00 копійок'],
    [2, 'Дві гривні 00 копійок'],
    [5, 'П’ять гривень 00 копійок'],
    [11, 'Одинадцять гривень 00 копійок'],
    [21.01, 'Двадцять одна гривня 01 копійка'],
    [112.22, 'Сто дванадцять гривень 22 копійки'],
    [749, 'Сімсот сорок дев’ять гривень 00 копійок'],
    [1000, 'Одна тисяча гривень 00 копійок'],
    [1250.5, 'Одна тисяча двісті п’ятдесят гривень 50 копійок'],
    [2000, 'Дві тисячі гривень 00 копійок'],
    [5400, 'П’ять тисяч чотириста гривень 00 копійок'],
    [11000, 'Одинадцять тисяч гривень 00 копійок'],
    [22990.99, 'Двадцять дві тисячі дев’ятсот дев’яносто гривень 99 копійок'],
    [1_000_000, 'Один мільйон гривень 00 копійок'],
    [2_301_002, 'Два мільйони триста одна тисяча дві гривні 00 копійок'],
    [0.5, 'Нуль гривень 50 копійок'],
  ])('%s → %s', (n, text) => {
    expect(amountInWords(n)).toBe(text);
  });

  it('гроші з пробілами й комою', () => {
    expect(money(1250.5)).toBe('1 250,50');
    expect(money(7490)).toBe('7 490,00');
    expect(money(0.1 + 0.2)).toBe('0,30');
  });
});
